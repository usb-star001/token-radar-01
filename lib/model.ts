// Radar-2: the token launch radar's model, written for token-radar-01.
//
// A protocol's implied value is what its token would be worth if the
// protocol's record stayed as it is. It is a model estimate, never a
// price and never a prediction that a token will be issued, or when.
//
//   implied = tvl_usd x category_multiple x growth_mult x maturity_mult x chain_mult
//
// Every factor comes from the snapshot's own figures only:
//   category_multiple  the protocol's category, from the table below
//   growth_mult        1 + clamp(change_7d, -40, +80) / 100 x 0.7
//   maturity_mult      0.65 + 0.35 x min(age_days, 1095) / 1095 (unknown age: 365 days)
//   chain_mult         1 + 0.04 x min(chains - 1, 3)
// No protocol name is ever special-cased: the same function scores
// every row, and the dashboard recomputes every row from the same
// figures so the page and board.json agree.
//
// The board ranks every rankable pre-token protocol in the snapshot:
// pre-token means the record carries no market cap, no CoinGecko id
// and no symbol. Live-token protocols are set aside, never ranked.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The radar-2 constants, as the dashboard states them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  chain_step: number;
  chain_max_extra: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.7,
  growth_floor: -40,
  growth_cap: 80,
  maturity_floor: 0.65,
  maturity_range: 0.35,
  maturity_days: 1095,
  unknown_age_days: 365,
  chain_step: 0.04,
  chain_max_extra: 3,
};

