/**
 * Category multiples, in the order they are matched (first match wins).
 * A category earns a higher multiple when a token is the natural way
 * its value accrues: trading venues first, then lending, then yield,
 * then asset-backed issuance, then curators, then chains and bridges.
 * Anything the table does not name takes the default 0.25.
 */
export interface CategoryBand {
  label: string;
  multiple: number;
  match: string[];
}

export const CATEGORY_BANDS: CategoryBand[] = [
  { label: 'Dexs / Perpetual / Derivatives', multiple: 0.45, match: ['dex', 'perpetual', 'derivative', 'basis trading'] },
  { label: 'Lending / CDP / Collateral', multiple: 0.35, match: ['lend', 'cdp', 'collateral'] },
  { label: 'Yield / Leveraged Farming / Liquidity Manager', multiple: 0.3, match: ['yield', 'leveraged farm', 'liquidity manager', 'farm'] },
  { label: 'RWA / Stablecoin / Payments', multiple: 0.2, match: ['rwa', 'stablecoin', 'payment'] },
  { label: 'Risk Curators / Onchain Capital Allocator', multiple: 0.15, match: ['risk curator', 'capital allocator'] },
  { label: 'Chain / Bridge / other', multiple: 0.12, match: ['chain', 'bridge'] },
];

export const DEFAULT_MULTIPLE = 0.25;

